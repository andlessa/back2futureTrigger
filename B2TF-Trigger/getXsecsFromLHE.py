#!/usr/bin/env python3

"""
Simple script to extract features from LHE files and save them as compressed numpy arrays for later use.
"""


import numpy as np
import os,gzip
from helper import getModelDict
import logging
import time,glob
import pandas as pd

FORMAT = '%(levelname)s in %(module)s.%(funcName)s(): %(message)s at %(asctime)s'
logging.basicConfig(format=FORMAT,datefmt='%m/%d/%Y %I:%M:%S %p')
logger = logging.getLogger()



def getXsecInfo(inputFile):
    """
    Reads an LHE file (plain text or .gz) and extracts the
    <MGGenerationInfo> ... </MGGenerationInfo> block from the header.

    Returns:
        str | None: Full MGGenerationInfo block as a single string,
        or None if not found.
    """

    blockLines = []
    opener = gzip.open if inputFile.endswith(".gz") else open
    with opener(inputFile, "rt", encoding="utf-8", errors="ignore") as f:
        in_mg_info = False
        mg_lines = []

        for line in f:
            if "<MGGenerationInfo>" in line:
                in_mg_info = True
                continue

            if in_mg_info:                
                if "</MGGenerationInfo>" in line:
                    break
                mg_lines.append(line.rstrip("\n"))

    blockLines = mg_lines[:]

    dataDict = {}
    for l in blockLines:
        l = l.replace("#", "")
        l = l.strip()        
        key,val = l.split(":",1)
        dataDict[key.strip()] = float(val.strip())

    return dataDict

def read_lhe_crossections(filepath):
    """
    Extract the total cross-sections from the LHE file for each individual process
    """

    block = []
    opener = gzip.open if filepath.endswith(".gz") else open

    xsecDict = {}
    in_event = False
    nevts = 0
    with opener(filepath, "rt", encoding="utf-8", errors="ignore") as f:
        for line in f:
            if "<event>" in line:
                in_event = True
                nevts += 1
                block = []
                continue
            if "</event>" in line:
                content = [ln.strip() for ln in block if ln.strip()]
                if not content:
                    continue

                header = content[0].split()
                nup, xwgtup = int(header[0]), float(header[2])

                particles = []
                for ln in content[1:1+nup]:
                    cols = ln.split()
                    if len(cols) < 13: continue
                    particles.append({
                        "pid": int(cols[0]), "status": int(cols[1]),
                        "px": float(cols[6]), "py": float(cols[7]), "pz": float(cols[8]),
                        "E":  float(cols[9]), "M": float(cols[10])
                    })

                incoming = sorted([p["pid"] for p in particles if p["status"] == -1])
                final = sorted([p["pid"] for p in particles if p["status"] == 1])
                procLabel = f"sigma({','.join(map(str,incoming))} -> {','.join(map(str,final))}) (pb)"
                xsecDict.setdefault(procLabel, 0.0)
                xsecDict[procLabel] += xwgtup

                in_event = False
                continue
            if in_event: block.append(line)

    # Sort cross-sections by value in descending order
    xsecDict = dict(sorted(xsecDict.items(), key=lambda item: item[1], reverse=True))
    # Rescale by the total number of events:
    if nevts > 0:
        for proc, xsec in xsecDict.items():
            xsecDict[proc] = xsec / nevts

    return xsecDict


def main(inputDir,outputFile):

    inputFiles = list(glob.glob(os.path.join(inputDir, "**/*.lhe"), recursive=True))
    inputFiles += list(glob.glob(os.path.join(inputDir, "**/*.lhe.gz"), recursive=True))
    dataList = []
    logger.info(f"Found {len(inputFiles)} LHE files in {inputDir}")
    for inputFile in inputFiles:
        logger.info(f"Extracting xsec from {inputFile}")
        xsecDict = getXsecInfo(inputFile)
        xsecDict.update(getModelDict(inputFile))
        xsecDict.update(read_lhe_crossections(inputFile))
        xsecDict['inputFile'] = inputFile
        logger.debug(xsecDict)
        dataList.append(xsecDict)
    keys = set().union(*(data.keys() for data in dataList))
    xsecDict = {key: [data.get(key, 0) for data in dataList] for key in keys}
    df = pd.DataFrame(xsecDict)
    if not outputFile.endswith(".csv"):
        outputFile += ".csv"
    df.to_csv(outputFile,index=False,float_format="%1.4e")
    logger.info(f"Saving xsecs to {outputFile}")


if __name__ == "__main__":
    
    import argparse    
    ap = argparse.ArgumentParser( description=
            "Reads an input LHE file generated by MadGraph and saves the extracted features as a compressed numpy array." )
    ap.add_argument('-d', '--inputdir', help='path to the LHE input directory.')
    ap.add_argument('-o', '--outputfile', help='name of the output file.',default=None)
    ap.add_argument('-v', '--verbose', default='info',
            help='verbose level (debug, info, warning or error). Default is info')


    t0 = time.time()
    args = ap.parse_args()
    inputDir = args.inputdir
    outputFile = args.outputfile

    level = args.verbose
    levels = { "debug": logging.DEBUG, "info": logging.INFO,
               "warn": logging.WARNING,
               "warning": logging.WARNING, "error": logging.ERROR }
    if level in levels:       
        logger.setLevel(level = levels[level])

    if not os.path.isdir(inputDir):
        logger.error(f"Input directory {inputDir} does not exist.")
        exit(1)

    if outputFile is None:
        outputFile = os.path.basename(inputDir)+"_xsecs.npz"
    if outputFile.endswith(".npz"):
        outputFile = outputFile.replace(".npz","")
    main(inputDir,outputFile)
            
    logger.info("Done in %3.2f min" %((time.time()-t0)/60.))    
